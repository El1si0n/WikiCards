/**
 * Détecte automatiquement le thème encyclopédique d'une carte Wikipédia
 * à partir de son titre, de sa description courte et de son extrait.
 */
export function detectCardTheme(card) {
  if (!card) return 'CULTURE';
  if (card.theme && WIKI_THEMES.some((t) => t.id === card.theme)) {
    return card.theme;
  }

  const text = `${card.title || ''} ${card.description || ''} ${
    card.extract || ''
  }`.toLowerCase();

  let bestTheme = 'SOCIETE';
  let bestScore = 0;

  for (const theme of WIKI_THEMES) {
    let score = 0;
    for (const kw of theme.keywords) {
      if (text.includes(kw)) {
        // Les mots-clés présents dès le titre ou la première phrase ont plus de poids
        const firstPart = text.slice(0, 140);
        score += firstPart.includes(kw) ? 3 : 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestTheme = theme.id;
    }
  }

  return bestTheme;
}

export function getThemeById(themeId) {
  return WIKI_THEMES.find((t) => t.id === themeId) || WIKI_THEMES[0];
}
